import { execFile } from "node:child_process"
import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"

const execFileAsync = promisify(execFile)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const roverDir = path.join(root, "public", "rover")
const files = ["app.enc.json", "milo.jpg", "prd.pdf"]
const outFile = path.join(root, "rover-assets.env")

const { stdout } = await execFileAsync("tar", ["-czf", "-", ...files], {
  cwd: roverDir,
  encoding: "buffer",
  maxBuffer: 20 * 1024 * 1024,
})
const encoded = Buffer.from(stdout).toString("base64")
const contents = `# Generated by npm run rover:encode — do not commit.\nROVER_ASSETS_TAR_B64=${encoded}\n`
await writeFile(outFile, contents)
console.log(`Wrote ${outFile} (${encoded.length} base64 chars)`)
console.log(
  "In Render: Environment → Add from .env → paste this file, then save & rebuild before merging the PR that removes these files from git.",
)
